"""YouTube publishing adapter using YouTube Data API v3.
Implements OAuth 2.0 with PKCE, resumable video uploading, and status verification.
"""
from __future__ import annotations

import json
import logging
import os
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, Optional, Tuple

from google.auth.exceptions import RefreshError
from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import Flow
from googleapiclient.discovery import build
from googleapiclient.errors import HttpError
from googleapiclient.http import MediaFileUpload

from ...core.config import settings
from ...security.crypto import create_signed_state, decrypt_token, encrypt_token, verify_signed_state
from ...services.accounts.credentials import get_google_client_config

logger = logging.getLogger("socialrelay.youtube")

SCOPES = [
    "https://www.googleapis.com/auth/youtube.upload",
    "https://www.googleapis.com/auth/youtube.readonly",
]


class YouTubeAdapterError(RuntimeError):
    pass


class YouTubeQuotaExceededError(YouTubeAdapterError):
    pass


class YouTubeAdapter:
    def __init__(self):
        self._pending_pkce: Dict[str, str] = {}
        self._lock = threading.Lock()
        if settings.effective_youtube_redirect_uri.startswith(("http://localhost", "http://127.0.0.1")):
            os.environ.setdefault("OAUTHLIB_INSECURE_TRANSPORT", "1")
        os.environ.setdefault("OAUTHLIB_RELAX_TOKEN_SCOPE", "1")

    def _get_client_config(self, db=None) -> Dict[str, Any]:
        """Load Google OAuth client credentials from encrypted DB settings, file, or env."""
        cfg = get_google_client_config(db)
        if cfg:
            return cfg
        raise YouTubeAdapterError(
            "YouTube client credentials not configured. Use the Account Setup Wizard in Accounts to upload client_secret.json."
        )

    def get_authorization_url(self, db=None) -> Tuple[str, str]:
        """Generate Google OAuth 2.0 authorization URL with PKCE and signed CSRF state."""
        config = self._get_client_config(db)
        flow = Flow.from_client_config(config, scopes=SCOPES, redirect_uri=settings.effective_youtube_redirect_uri)
        flow.code_verifier = None  # Will be auto-generated by flow
        state_nonce = create_signed_state("youtube_oauth")

        auth_url, state = flow.authorization_url(
            access_type="offline",
            include_granted_scopes="true",
            prompt="consent",
            state=state_nonce,
        )

        with self._lock:
            self._pending_pkce[state_nonce] = getattr(flow, "code_verifier", None)

        return auth_url, state_nonce

    def handle_oauth_callback(self, code: str, state: str, db=None) -> Dict[str, Any]:
        """Exchange OAuth authorization code for credentials and retrieve channel details."""
        if not verify_signed_state(state):
            raise YouTubeAdapterError("OAuth state validation failed. The request may have expired or been tampered with.")

        with self._lock:
            code_verifier = self._pending_pkce.pop(state, None)

        config = self._get_client_config(db)
        flow = Flow.from_client_config(config, scopes=SCOPES, redirect_uri=settings.effective_youtube_redirect_uri)
        if code_verifier:
            flow.code_verifier = code_verifier

        flow.fetch_token(code=code)
        creds: Credentials = flow.credentials

        # Retrieve channel identity
        service = build("youtube", "v3", credentials=creds, cache_discovery=False)
        channels_res = service.channels().list(part="snippet,contentDetails", mine=True).execute()
        items = channels_res.get("items", [])
        if not items:
            raise YouTubeAdapterError("This Google account has no associated YouTube channel. Please create a channel first.")

        item = items[0]
        channel_id = item["id"]
        title = item["snippet"]["title"]
        custom_url = item["snippet"].get("customUrl")
        thumbnail = item["snippet"].get("thumbnails", {}).get("default", {}).get("url")

        creds_json = creds.to_json()
        encrypted_token = encrypt_token(creds_json)

        return {
            "channel_id": channel_id,
            "title": title,
            "custom_url": custom_url,
            "avatar_url": thumbnail,
            "encrypted_token": encrypted_token,
            "permissions": SCOPES,
            "expiry": creds.expiry.isoformat() if creds.expiry else None,
        }

    def get_authenticated_service(self, encrypted_token: str):
        """Build an authenticated YouTube service, refreshing tokens automatically if expired."""
        plaintext_json = decrypt_token(encrypted_token)
        creds_data = json.loads(plaintext_json)
        creds = Credentials.from_authorized_user_info(creds_data, scopes=SCOPES)

        if creds.expired and creds.refresh_token:
            try:
                creds.refresh(Request())
            except RefreshError as e:
                raise YouTubeAdapterError(f"OAuth token has expired or was revoked. Reconnect account: {e}")

        return build("youtube", "v3", credentials=creds, cache_discovery=False)

    def upload_video(
        self,
        encrypted_token: str,
        video_path: Path,
        title: str,
        description: str,
        tags: Optional[list[str]] = None,
        privacy: str = "private",
        category_id: str = "24",
        made_for_kids: bool = False,
        progress_callback: Optional[Callable[[int], None]] = None,
    ) -> Dict[str, Any]:
        """Perform a chunked resumable upload to YouTube."""
        if not video_path.exists() or video_path.stat().st_size == 0:
            raise YouTubeAdapterError(f"Video file missing or empty: {video_path}")

        service = self.get_authenticated_service(encrypted_token)

        body = {
            "snippet": {
                "title": title[:100],
                "description": description[:5000],
                "tags": tags or [],
                "categoryId": category_id,
            },
            "status": {
                "privacyStatus": privacy if privacy in ("private", "unlisted", "public") else "private",
                "selfDeclaredMadeForKids": made_for_kids,
            },
        }

        # 5 MB chunk size for resumable uploads
        media = MediaFileUpload(str(video_path), mimetype="video/mp4", chunksize=5 * 1024 * 1024, resumable=True)

        try:
            request = service.videos().insert(part="snippet,status", body=body, media_body=media)
            response = None
            while response is None:
                status, response = request.next_chunk()
                if status and progress_callback:
                    pct = int(status.progress() * 100)
                    progress_callback(pct)

            video_id = response.get("id")
            if not video_id:
                raise YouTubeAdapterError("Upload finished but YouTube did not return a video ID.")

            video_url = f"https://youtu.be/{video_id}"
            logger.info(f"Successfully uploaded video to YouTube: {video_url}")
            return {
                "video_id": video_id,
                "video_url": video_url,
                "status": "published",
            }
        except HttpError as exc:
            reason = ""
            try:
                err_data = json.loads(exc.content)
                reason = err_data["error"]["errors"][0]["reason"]
            except Exception:
                pass

            if reason == "quotaExceeded":
                raise YouTubeQuotaExceededError(
                    "YouTube Data API daily quota exceeded. YouTube grants 10,000 units/day (approx 6 uploads). Quota resets at midnight Pacific Time."
                )
            if reason == "uploadLimitExceeded":
                raise YouTubeQuotaExceededError("Your YouTube channel reached its daily upload limit. Please retry tomorrow.")

            raise YouTubeAdapterError(f"YouTube upload failed: {reason or exc.reason} (HTTP {exc.resp.status})")


youtube_adapter = YouTubeAdapter()
